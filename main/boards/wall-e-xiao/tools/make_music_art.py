"""Turns pictures into the music screen's "music icon 3" and "music icon 4": scaled to 148 x 148 (what fits between the top and the Winamp bars) and written as RGB565
(with error-diffusion dithering, so the dark gradients do not band on the little screen) into walle_music_art.inc next to the board code.

    python make_music_art.py <picture for icon 3> <picture for icon 4>      (needs Pillow)

walle_music_art.inc is NOT in git (the pictures are not mine to publish): without it the firmware still builds, and icons 3 and 4 then show the drawn icons 1 and 2.
Transparent corners (rounded app icons) become black, the colour of the screen behind the picture.
"""
import sys
from pathlib import Path

from PIL import Image

SIZE = 148
OUT = Path(__file__).resolve().parents[1] / "walle_music_art.inc"


def to_565(path):
    im = Image.open(path).convert("RGBA")
    bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
    im = Image.alpha_composite(bg, im).convert("RGB").resize((SIZE, SIZE), Image.LANCZOS)
    px = [[list(map(float, im.getpixel((x, y)))) for x in range(SIZE)] for y in range(SIZE)]
    out = []
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b = px[y][x]
            q = []
            for c, bits in ((r, 5), (g, 6), (b, 5)):
                step = 255.0 / ((1 << bits) - 1)
                v = min((1 << bits) - 1, max(0, int(round(c / step))))
                q.append(v)
                err = c - v * step
                # Floyd-Steinberg: pass the rounding error to the neighbours
                ch = len(q) - 1
                if x + 1 < SIZE:
                    px[y][x + 1][ch] += err * 7 / 16
                if y + 1 < SIZE:
                    if x > 0:
                        px[y + 1][x - 1][ch] += err * 3 / 16
                    px[y + 1][x][ch] += err * 5 / 16
                    if x + 1 < SIZE:
                        px[y + 1][x + 1][ch] += err * 1 / 16
            out.append((q[0] << 11) | (q[1] << 5) | q[2])
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    lines = ["// Generated by tools/make_music_art.py - not in git. Two 148 x 148 RGB565 pictures for the music screen (music icon 3 and 4).",
             "#pragma once", "#include <cstdint>", f"constexpr int kMusicArtSize = {SIZE};"]
    for n, path in zip((3, 4), sys.argv[1:3]):
        data = to_565(path)
        lines.append(f"static const uint16_t kMusicArt{n}[{SIZE * SIZE}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join(f"0x{v:04x}" for v in data[i:i + 24]) + ",")
        lines.append("};")
        print(f"icon {n}: {path} -> {SIZE}x{SIZE}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT, f"({OUT.stat().st_size // 1024} KB source, {2 * 2 * SIZE * SIZE // 1024} KB in the firmware)")


if __name__ == "__main__":
    main()
